const languageSelect = document.getElementById('languageSelect');

function updateTexts(lang) {
  document.querySelectorAll('[data-key]').forEach(el => {
    const key = el.getAttribute('data-key');
    el.innerHTML = translations[lang][key] || key;  // <-- innerHTML au lieu de textContent
  });
}

// Met à jour quand l'utilisateur change la langue
languageSelect.addEventListener('change', function () {
  const selectedLang = this.value;
  updateTexts(selectedLang);

  // Enregistre la langue dans l'URL
  const url = new URL(window.location.href);
  url.searchParams.set('lang', selectedLang);
  window.history.replaceState(null, '', url); // modifie sans recharger
});

// Applique la langue au chargement
window.addEventListener('DOMContentLoaded', () => {
  const params = new URLSearchParams(window.location.search);
  const lang = params.get('lang') || 'en';
  languageSelect.value = lang;
  updateTexts(lang);
});
